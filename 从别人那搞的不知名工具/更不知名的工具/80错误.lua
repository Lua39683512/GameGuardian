lsq=gg.prompt({
""
},{
gg.getFile()
},{
"file"
})

Y=io.open(lsq[1],"r"):read("*a")

T=[=[
 if nil then local a='' end print("")
 while (nil) do local a="" end print("")
]=]

Y = Y:gsub("then","then\n\n"..T)

file=io.open(lsq[1]..".lua","w")

Y=load(Y)

spritend=string.dump(Y,true,true)

--进行反编译未知错误操作
spritend,error=spritend:gsub(string.char(0x1B,0x00,0x00, 0x00, 0x17, 0x00 ,0x00 ,0x80,0x01),string.char(0x1B, 0x00, 0x00, 0x00 ,0x17, 0x00 ,0x00 ,0x80 ,0x17))

spritend,error=spritend:gsub(string.char(0x1B,0x00,0x00, 0x00, 0x17, 0x40 ,0x00 ,0x80,0x01),string.char(0x1B, 0x00, 0x00, 0x00 ,0x17, 0x40 ,0x00 ,0x80 ,0x99))

spritend,error=spritend:gsub(string.char(0x17 ,0x80 ,0xFE ,0x7F ,0x06),
string.char(0x17 ,0x80 ,0x1B ,0x7F ,0x06))

spritend,error=spritend:gsub(string.char(0x1F ,0x00 ,0x80 ,0x00 ),
string.char(0x1F ,0x00 ,0x80 ,0xAB))

file:write(spritend)            